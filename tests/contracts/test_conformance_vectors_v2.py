"""Extended conformance against cowprotocol/services (fixture schema v2).

Covers every chain the orderbook runs on, partially fillable orders, batch and
single order cancellations, and app-data hashing/validation. Generated by
``cowdao-grants/cow-rs`` ``tools/conformance-gen`` from the services commit in
``services_sha``.
"""

import json
from pathlib import Path

import pytest
from eth_account import Account
from eth_typing import HexStr
from eth_utils.conversions import to_hex
from eth_utils.crypto import keccak
from web3 import Web3

from cowdao_cowpy.app_data.app_data_doc import AppDataDoc
from cowdao_cowpy.common.chains import Chain
from cowdao_cowpy.contracts.domain import TypedDataDomain, domain
from cowdao_cowpy.contracts.order import (
    Order,
    compute_order_uid,
    hash_order,
    hash_order_cancellations,
)
from cowdao_cowpy.contracts.sign import (
    SigningScheme,
    sign_order,
    sign_order_cancellations,
)

FIXTURE = Path(__file__).parent / "fixtures" / "conformance_vectors.v2.json"
V2 = json.loads(FIXTURE.read_text())
TEST_KEY = "0xac0974bec39a17e36ba4a6b4d238ff944bacb478cbed5efcae784d7bf4f2ff80"
SIGNER = Account.from_key(TEST_KEY)
SETTLEMENT = Web3.to_checksum_address(V2["settlement"])
ETHSIGN_PREFIX = b"\x19Ethereum Signed Message:\n32"

# The v1 base order, repeated here so this file stands alone.
BASE_ORDER = Order(
    sell_token=Web3.to_checksum_address("0x" + "01" * 20),
    buy_token=Web3.to_checksum_address("0x" + "02" * 20),
    receiver=Web3.to_checksum_address("0x" + "03" * 20),
    sell_amount=str(0x0246DDF97976680000),
    buy_amount=str(0xB98BC829A6F90000),
    valid_to=1_893_456_000,
    app_data=to_hex(keccak(b"cow-rs conformance vector")),
    fee_amount=str(0x0DE0B6B3A7640000),
    kind="sell",
    partially_fillable=False,
    sell_token_balance="erc20",
    buy_token_balance="erc20",
)

CHAIN_BY_ID = {chain.chain_id.value: chain for chain in Chain}


def _sig_hex(sig):
    return "0x" + sig["r"][2:] + sig["s"][2:] + f"{sig['v']:02x}"


def _digest_for(scheme: SigningScheme, eip712_digest: bytes) -> bytes:
    return (
        keccak(ETHSIGN_PREFIX + eip712_digest)
        if scheme == SigningScheme.ETHSIGN
        else eip712_digest
    )


def _check_scheme(result, scheme, eip712_digest, signature_hex):
    assert to_hex(_digest_for(scheme, eip712_digest)) == result["digest"]
    assert signature_hex.lower() == _sig_hex(result["signature"]).lower()
    recovered = Account._recover_hash(
        _digest_for(scheme, eip712_digest), signature=signature_hex
    )
    assert recovered.lower() == result["recovered_owner"]


def test_signer_matches():
    assert SIGNER.address.lower() == V2["signer"]


@pytest.mark.parametrize(
    "v", V2["chains"], ids=[f"chain_{c['chain_id']}" for c in V2["chains"]]
)
def test_every_supported_chain_domain_matches_services(v):
    chain = CHAIN_BY_ID[
        v["chain_id"]
    ]  # KeyError here means cow-py lacks a chain the orderbook runs on
    dom = domain(chain, SETTLEMENT)
    assert dom.chainId == v["chain_id"]
    digest = bytes(hash_order(dom, BASE_ORDER))
    assert compute_order_uid(dom, BASE_ORDER, SIGNER.address).lower() == v["uid"]
    for scheme, key in (
        (SigningScheme.EIP712, "eip712"),
        (SigningScheme.ETHSIGN, "ethsign"),
    ):
        sig = sign_order(dom, BASE_ORDER, SIGNER, scheme)
        _check_scheme(v[key], scheme, digest, sig.data)


@pytest.mark.parametrize(
    "v",
    V2["partially_fillable_orders"],
    ids=[o["id"] for o in V2["partially_fillable_orders"]],
)
def test_partially_fillable_orders_match_services(v):
    dom = TypedDataDomain("Gnosis Protocol", "v2", v["chain_id"], SETTLEMENT)
    order = Order(
        **{
            **{
                f.name: getattr(BASE_ORDER, f.name)
                for f in BASE_ORDER.__dataclass_fields__.values()
            },
            "kind": v["kind"],
            "partially_fillable": v["partially_fillable"],
            "sell_amount": v["sell_amount"],
            "buy_amount": v["buy_amount"],
            "fee_amount": v["fee_amount"],
        }
    )
    digest = bytes(hash_order(dom, order))
    assert compute_order_uid(dom, order, SIGNER.address).lower() == v["uid"]
    for scheme, key in (
        (SigningScheme.EIP712, "eip712"),
        (SigningScheme.ETHSIGN, "ethsign"),
    ):
        _check_scheme(
            v[key], scheme, digest, sign_order(dom, order, SIGNER, scheme).data
        )


@pytest.mark.parametrize(
    "v",
    V2["batch_cancellations"],
    ids=[f"batch_{len(b['order_uids'])}" for b in V2["batch_cancellations"]],
)
def test_batch_cancellations_match_services(v):
    dom = TypedDataDomain("Gnosis Protocol", "v2", v["chain_id"], SETTLEMENT)
    digest = Web3.to_bytes(
        hexstr=HexStr(hash_order_cancellations(dom, v["order_uids"]))
    )
    assert to_hex(digest) == v["eip712"]["digest"]
    for scheme, key in (
        (SigningScheme.EIP712, "eip712"),
        (SigningScheme.ETHSIGN, "ethsign"),
    ):
        sig = sign_order_cancellations(dom, v["order_uids"], SIGNER, scheme)
        _check_scheme(v[key], scheme, digest, sig.data)


