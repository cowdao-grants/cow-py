@pytest.mark.parametrize("v", V2["app_data"], ids=[a["id"] for a in V2["app_data"]])
def test_app_data_hash_and_cid_match_services(v):
    doc = AppDataDoc(app_data_doc_string=v["document"])
    assert doc.to_hex() == v["hash"]
    assert doc.to_cid() == v["cid"]


def test_cowpy_default_app_data_is_the_services_hashed_document():
    """The document cow-py registers by default hashes, under services' rules, to the
    hash cow-py puts in orders (and that the orderbook has on record)."""
    from cowdao_cowpy.app_data.utils import DEFAULT_APP_DATA_HASH, generate_app_data

    vector = next(a for a in V2["app_data"] if a["id"] == "cowpy_default_1_0_1")
    created = generate_app_data()
    assert created.app_data_object.fullAppData is not None
    assert created.app_data_object.fullAppData.root == vector["document"]
    assert created.app_data_hash.root == vector["hash"] == DEFAULT_APP_DATA_HASH
    assert vector["valid"] is True
